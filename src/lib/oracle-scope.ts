export function isAtlasScopedQuestion(message: string): boolean {
  const normalized = message.toLowerCase();

  return (
    DIRECT_ATLAS_TERMS.some((term) => normalized.includes(term)) ||
    CHINESE_ATLAS_TERMS.some((term) => message.includes(term))
  );
}
